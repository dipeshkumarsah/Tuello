-- UUID v7: 48-bit unix ms timestamp + version/variant + random. Time-ordered for index locality.
CREATE FUNCTION app.uuid_generate_v7() RETURNS uuid
LANGUAGE plpgsql VOLATILE PARALLEL SAFE AS $$
DECLARE
  ts bytea := substring(int8send(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint) FROM 3);
  b  bytea := ts || substring(uuid_send(gen_random_uuid()) FROM 7 FOR 10);
BEGIN
  b := set_byte(b, 6, (b'0111' || get_byte(b, 6)::bit(4))::bit(8)::int);
  b := set_byte(b, 8, (b'10' || get_byte(b, 8)::bit(6))::bit(8)::int);
  RETURN encode(b, 'hex')::uuid;
END
$$;

-- Tenant context. Raises when missing so that a query without SET LOCAL app.tenant_id fails
-- loudly instead of silently returning nothing.
CREATE FUNCTION app.current_tenant_id() RETURNS uuid
LANGUAGE plpgsql STABLE PARALLEL SAFE AS $$
DECLARE
  v text := current_setting('app.tenant_id', true);
BEGIN
  IF v IS NULL OR v = '' THEN
    RAISE EXCEPTION 'tenant context missing: app.tenant_id is not set for this transaction'
      USING ERRCODE = 'TN001';
  END IF;
  RETURN v::uuid;
END
$$;

CREATE FUNCTION app.current_user_id() RETURNS uuid
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT nullif(current_setting('app.user_id', true), '')::uuid
$$;

GRANT EXECUTE ON FUNCTION app.uuid_generate_v7(), app.current_tenant_id(), app.current_user_id()
  TO tuello_app, tuello_definer;

