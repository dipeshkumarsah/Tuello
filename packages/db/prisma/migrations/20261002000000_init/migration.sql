-- SECURITY DEFINER lookups (owned by tuello_definer). Each returns the minimum it must.
-- ---------------------------------------------------------------------------------------------
CREATE FUNCTION app.tenant_by_slug(p_slug text)
RETURNS TABLE (id uuid, slug text, name text, status tenant_status)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT t.id, t.slug, t.name, t.status FROM tenants t
  WHERE t.slug = lower(p_slug) AND t.deleted_at IS NULL
$$;

CREATE FUNCTION app.tenant_by_domain(p_hostname text)
RETURNS TABLE (id uuid, slug text, name text, status tenant_status)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT t.id, t.slug, t.name, t.status
  FROM tenant_domains d JOIN tenants t ON t.id = d.tenant_id
  WHERE d.hostname = lower(p_hostname) AND d.status = 'verified'
    AND d.deleted_at IS NULL AND t.deleted_at IS NULL
$$;

CREATE FUNCTION app.slug_available(p_slug text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT NOT EXISTS (SELECT 1 FROM tenants WHERE slug = lower(p_slug))
$$;

