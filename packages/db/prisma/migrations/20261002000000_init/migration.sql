-- Pending custom domains due for a DNS check: backoff grows with attempts (2^n minutes, max 6 h).
CREATE FUNCTION app.domains_due_for_check(p_limit int)
RETURNS TABLE (id uuid, tenant_id uuid)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT d.id, d.tenant_id FROM tenant_domains d
  WHERE d.status = 'pending' AND d.deleted_at IS NULL
    AND (d.last_checked_at IS NULL
         OR d.last_checked_at < now() - least(interval '6 hours', interval '1 minute' * power(2, least(d.check_attempts, 12))))
  ORDER BY d.last_checked_at NULLS FIRST
  LIMIT least(p_limit, 500)
$$;

-- Claim a batch of unpublished outbox events with a lease, skipping rows other workers hold.
CREATE FUNCTION app.claim_outbox_events(p_limit int, p_lease_seconds int)
RETURNS SETOF outbox_events
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  UPDATE outbox_events o
  SET locked_until = now() + make_interval(secs => p_lease_seconds), attempts = o.attempts + 1
  WHERE o.id IN (
    SELECT id FROM outbox_events
    WHERE published_at IS NULL AND (locked_until IS NULL OR locked_until < now())
    ORDER BY occurred_at
    LIMIT least(p_limit, 1000)
    FOR UPDATE SKIP LOCKED
  )
  RETURNING o.*
$$;

CREATE FUNCTION app.mark_outbox_published(p_ids uuid[]) RETURNS integer
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  WITH done AS (
    UPDATE outbox_events SET published_at = now(), locked_until = NULL
    WHERE id = ANY(p_ids) AND published_at IS NULL
    RETURNING 1
  )
  SELECT count(*)::int FROM done
$$;

-- Store a verified third-party webhook. duplicate = true when this provider event was seen before.
CREATE FUNCTION app.record_webhook_event(
  p_provider text, p_provider_event_id text, p_type text, p_payload jsonb, p_tenant_id uuid
) RETURNS TABLE (id uuid, duplicate boolean)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE
  v_id uuid;
BEGIN
  INSERT INTO webhook_events (provider, provider_event_id, type, payload, tenant_id)
  VALUES (p_provider, p_provider_event_id, p_type, p_payload, p_tenant_id)
  ON CONFLICT (provider, provider_event_id) DO NOTHING
  RETURNING webhook_events.id INTO v_id;
  IF v_id IS NOT NULL THEN
    RETURN QUERY SELECT v_id, false;
  ELSE
    RETURN QUERY SELECT w.id, true FROM webhook_events w
      WHERE w.provider = p_provider AND w.provider_event_id = p_provider_event_id;
  END IF;
END
$$;

